// Builds the package from icons/: one React icon per drawing, the typed list of icon names, and the sprite.
// Usage: node scripts/generate-icons.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

import { parseIcon, ROOT_DEFAULTS } from './svg.mjs';

const ICONS_DIR = new URL('../icons/', import.meta.url);
const OUTPUT_DIR = new URL('../src/generated/', import.meta.url);
const HEADER = '// Generated by scripts/generate-icons.mjs from icons/. Do not edit by hand.';

/**
 * Turns an icon name such as Arrow_Down_LG into the export name RefineIconArrowDownLG.
 */
const toExportName = (name) => {
  return `RefineIcon${name
    .split('_')
    .map((part) => {
      return part[0].toUpperCase() + part.slice(1);
    })
    .join('')}`;
};

const icons = readdirSync(ICONS_DIR)
  .filter((file) => {
    return file.endsWith('.svg');
  })
  .map((file) => {
    const name = file.slice(0, -'.svg'.length);
    if (!/^[A-Za-z0-9]+(_[A-Za-z0-9]+)*$/.test(name)) throw new Error(`${file} is not a Name_Like_This.`);
    return { name, ...parseIcon(name, readFileSync(new URL(file, ICONS_DIR), 'utf8')) };
  })
  .sort((a, b) => {
    return a.name.localeCompare(b.name);
  });

mkdirSync(OUTPUT_DIR, { recursive: true });

writeFileSync(
  new URL('refine-icons.ts', OUTPUT_DIR),
  [
    HEADER,
    "import { createRefineIcon } from '../create-refine-icon';",
    '',
    ...icons.map(({ name, viewBox, paths }) => {
      return `export const ${toExportName(name)} = /* @__PURE__ */ createRefineIcon('${name}', '${viewBox}', ${JSON.stringify(paths)});`;
    }),
    '',
  ].join('\n'),
);

// The name map lives in its own entry, so an app that imports one icon by its component never pulls in the whole set.
writeFileSync(
  new URL('refine-icon-names.ts', OUTPUT_DIR),
  [
    HEADER,
    'import {',
    ...icons.map(({ name }) => {
      return `  ${toExportName(name)},`;
    }),
    "} from './refine-icons';",
    '',
    '/** Every Refine icon under its name, so an app can keep icon names in data. */',
    'export const REFINE_ICON_NAMES = {',
    ...icons.map(({ name }) => {
      return `  ${name}: ${toExportName(name)},`;
    }),
    '} as const;',
    '',
    '/** The name of a Refine icon, such as `Arrow_Down_LG`. */',
    'export type IconName = keyof typeof REFINE_ICON_NAMES;',
    '',
  ].join('\n'),
);

const symbolDefaults = Object.entries(ROOT_DEFAULTS)
  .map(([name, value]) => {
    return ` ${name}="${value}"`;
  })
  .join('');

writeFileSync(
  new URL('sprite.svg', OUTPUT_DIR),
  [
    '<svg xmlns="http://www.w3.org/2000/svg">',
    ...icons.map(({ name }) => {
      const source = readFileSync(new URL(`${name}.svg`, ICONS_DIR), 'utf8');
      const root = source.match(/<svg\b[^>]*>/)[0];
      const body = source.slice(source.indexOf(root) + root.length, source.lastIndexOf('</svg>')).trim();
      const { viewBox } = icons.find((icon) => {
        return icon.name === name;
      });
      return `  <symbol id="${name}" viewBox="${viewBox}"${symbolDefaults}>${body.replaceAll(/\s*\n\s*/g, '')}</symbol>`;
    }),
    '</svg>',
    '',
  ].join('\n'),
);

console.log(`Generated ${icons.length} icons.`);
